const greet = function (name) {
    return `Hello, ${name}!`;
}

// Function with Argument and return
function greet1(name1) {
    return `Hello, ${name1}!`;
}

// Function as Expression
const greet2 = function (name1) {
    return `Hello, ${name1}!`;
}


console.log(greet("Bob"));
console.log(greet1("Tom"));
console.log(greet2("Ray"));
